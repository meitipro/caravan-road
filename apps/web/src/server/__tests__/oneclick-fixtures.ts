export interface Call { method: string; path: string; query: URLSearchParams; headers: Record<string, string>; body: Record<string, unknown> | null; init: RequestInit }

export type StatusName = (typeof DOC_STATUSES)[number];

interface StoredQuote { response: Record<string, unknown>; status: StatusName; swapDetails: Record<string, unknown> }

/** Stateful 1Click mock: /v0/tokens, /v0/quote (dry and real), /v0/status, /v0/deposit/submit. */
export class MockOneClick {
  calls: Call[] = [];
  quotes = new Map<string, StoredQuote>();
  tokens: unknown = tokenList();
  /** Override the next answers per path: return a Response to short-circuit. */
  override: Array<(c: Call) => Response | null> = [];
  tamper: (resp: Record<string, unknown>, req: Record<string, unknown>) => void = () => undefined;
  private n = 0;

  json(body: unknown, status = 200): Response {
    return new Response(JSON.stringify(body), { status, headers: { "content-type": "application/json" } });
  }

  readonly fetch: FetchLike = async (input, init) => {
    const u = new URL(input);
    const headers: Record<string, string> = {};
    new Headers(init.headers).forEach((v, k) => { headers[k] = v; });
    const call: Call = {
      method: init.method ?? "GET", path: u.pathname, query: u.searchParams, headers,
      body: typeof init.body === "string" ? (JSON.parse(init.body) as Record<string, unknown>) : null, init,
    };
    this.calls.push(call);
    for (const o of this.override) {
      const r = o(call);
      if (r) return r;
    }
    if (call.method === "GET" && call.path === "/v0/tokens") return this.json(this.tokens);
    if (call.method === "POST" && call.path === "/v0/quote") return this.quote(call.body!);
    if (call.method === "GET" && call.path === "/v0/status") {
      const q = this.quotes.get(call.query.get("depositAddress") ?? "");
      if (!q) return this.json(DOC_BAD_REQUEST, 404);
      return this.json({ correlationId: DOC_CORRELATION_ID, quoteResponse: q.response, status: q.status, updatedAt: "2019-08-24T14:15:22Z", swapDetails: q.swapDetails });
    }
    if (call.method === "POST" && call.path === "/v0/deposit/submit") return this.json({ ok: true });
    return this.json(DOC_BAD_REQUEST, 400);
  };

  private depositAddress(req: Record<string, unknown>): string {
    this.n += 1;
    // origin = NEAR USDC -> a 64-hex implicit NEAR account; otherwise an EVM-looking address (test placeholders)
    if (req.originAsset === TEST_USDC_ASSET_ID) return this.n.toString(16).padStart(64, "0");
    return `0x${this.n.toString(16).padStart(40, "0")}`;
  }

  private quote(req: Record<string, unknown>): Response {
    const dry = req.dry === true;
    const quote: Record<string, unknown> = { ...DOC_QUOTE_AMOUNTS, amountIn: req.amount };
    if (!dry) {
      quote.depositAddress = this.depositAddress(req);
      quote.deadline = req.deadline;
      quote.timeWhenInactive = req.deadline;
    }
    const response: Record<string, unknown> = {
      correlationId: DOC_CORRELATION_ID, timestamp: "2019-08-24T14:15:22Z", signature: DOC_SIGNATURE_FIELD_PRESENT, quoteRequest: { ...req }, quote,
    };
    this.tamper(response, req);
    if (!dry) this.quotes.set(String(quote.depositAddress), { response, status: "PENDING_DEPOSIT", swapDetails: { intentHashes: [], nearTxHashes: [], originChainTxHashes: [], destinationChainTxHashes: [] } });
    return this.json(response);
  }

  /** Test control: move a quote to a status; SUCCESS adds the docs' swapDetails example. */
  setStatus(depositAddress: string, status: StatusName, swapDetails?: Record<string, unknown>): void {
    const q = this.quotes.get(depositAddress);
    if (!q) throw new Error("unknown quote");
    q.status = status;
    if (swapDetails) q.swapDetails = swapDetails;
    else if (status === "SUCCESS") q.swapDetails = { ...DOC_SWAP_DETAILS, refundedAmount: undefined, refundReason: undefined };
  }

  last(path: string, method?: string): Call {
    const c = [...this.calls].reverse().find((x) => x.path === path && (!method || x.method === method));
    if (!c) throw new Error(`no call to ${path}`);
    return c;
  }
  count(path: string, method?: string): number {
    return this.calls.filter((x) => x.path === path && (!method || x.method === method)).length;
  }
}
