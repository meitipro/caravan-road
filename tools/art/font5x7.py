GLYPHS = {ch: [row for row in spec.split("|")] for ch, spec in _G.items()}
GLYPH_W, GLYPH_H = 5, 7


def text_width(text, scale=1, spacing=1):
    n = len(text)
    return 0 if n == 0 else n * GLYPH_W * scale + (n - 1) * spacing * scale


def draw_text(canvas, x, y, text, color, scale=1, spacing=1):
    """Draw uppercase text (lowercase is upper-cased); returns the width drawn."""
    cx = x
    for ch in text.upper():
        rows = GLYPHS.get(ch)
        if rows is None:
            rows = GLYPHS[" "]
        for gy, row in enumerate(rows):
            for gx, bit in enumerate(row):
                if bit == "#":
                    canvas.rect(cx + gx * scale, y + gy * scale, scale, scale, color)
        cx += (GLYPH_W + spacing) * scale
    return text_width(text, scale, spacing)


def text_canvas(text, color, scale=1, spacing=1):
    c = Canvas(max(text_width(text, scale, spacing), 1), GLYPH_H * scale)
    draw_text(c, 0, 0, text, color, scale, spacing)
    return c
